def events_of(day):
    y, m = day[:4], day[:7]
    path = os.path.join(ROOT, 'data', 'events', y, m + '.csv')
    with open(path, encoding='utf-8') as f:
        return [r for r in csv.DictReader(f) if r['t'].startswith(day)]


def pick(day, box):
    lo, hi, w, e = box
    best = None
    for r in events_of(day):
        try:
            la, lo_, m = float(r['lat']), float(r['lon']), float(r['mag'])
        except ValueError:
            continue
        if lo <= la <= hi and w <= lo_ <= e and (best is None or m > float(best['mag'])):
            best = r
    return best


def main():
    out, bad = [], []
    for name, alias, day, box, src, m_list, note in LIST:
        r = pick(day, box)
        if r is None:
            bad.append(day + ' ' + name + '：その日・その範囲に地震が無い')
            continue
        m = float(r['mag'])
        if m_list is not None and abs(m - m_list) > 0.05:
            bad.append('%s %s：一覧は M%.1f、選んだ地震は M%.1f（%s）' % (day, name, m_list, m, r['t']))
        out.append({'name': name, 'alias': alias, 'note': note, 'src': SRC_A if src == 'A' else SRC_B,
                    't': r['t'], 'lat': float(r['lat']), 'lon': float(r['lon']),
                    'dep': None if r['dep'] == '' else float(r['dep']), 'mag': m, 'maxi': r['maxi']})
        print('%-34s %s  %.2f %.2f  M%.1f  震度%s' % (name, r['t'], float(r['lat']), float(r['lon']), m, r['maxi'] or '-'))
    if bad:
        print('\n止めました：\n' + '\n'.join(bad))
        sys.exit(1)
    doc = {'about': '有名な地震（テロップ）。名前・震災名・日付は気象庁の一覧のとおり。時刻・震源・M はこのデータの、その日・その範囲で M のいちばん大きい地震'
                    '（research/build_named_quakes.py）',
           'sources': {SRC_A: 'https://www.jma.go.jp/jma/kishou/know/meishou/meishou_ichiran.html',
                       SRC_B: 'https://www.data.jma.go.jp/eqev/data/higai/higai-1995.html'},
           'quakes': out}
    with open(os.path.join(ROOT, 'data', 'overlays', 'named_quakes.json'), 'w', encoding='utf-8') as f:
        json.dump(doc, f, ensure_ascii=False, indent=1)
    print('\n%d 件を書きました' % len(out))


if __name__ == '__main__':
    main()
